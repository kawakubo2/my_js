let x = 10;
console.log(`x=${x}`);
x = x + 1;
console.log(`x = x + 1 ---> ${x}`);
x += 1;
console.log(`x += 1 ---> ${x}`);
x++;
console.log(`x++ ---> ${x}`);

x -= 3;
console.log(`x -= 10 ---> x=${x}`);

x *= 4;
console.log(`x *= 4 ---> x=${x}`);

x /= 8;
console.log(`x /= 8 ---> x=${x}`);

x %= 2;
console.log(`x %= 2 ---> x=${x}`);

let y = 3;
y **= 3;
console.log(y);

