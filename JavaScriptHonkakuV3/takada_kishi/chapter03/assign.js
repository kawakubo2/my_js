let a = 10;
console.log(`a = ${a}`);

// 複合代入演算子
console.log(`a += 5 ---> ${a += 5}`); // a += 5 ---> a = a + 5
console.log(`a -= 8 ---> ${a -= 8}`); // a -= 8 ---> a = a - 8;
console.log(`a *= 3 ---> ${a *= 3}`); // a *= 3 ---> a = a * 3;
console.log(`a /= 7 ---> ${a /= 7}`); // a /= 7 ---> a = a / 7;

let b = 2;
console.log(`(b ** 10) bの10乗 ---> ${b ** 10}`);

let c = 5;
console.log(`c **= 3 ---> ${c **= 3}`); // c **= 3 ---> c = c ** 3;